# MPSKit reference for the open golden chain (design O3).
#
#     julia --project=reference/mpskit reference/mpskit/golden_chain.jl
#
# writes reference/mpskit/fixtures/golden_chain.txt. CI never runs this; the
# Rust test `mpskit_fixture` reads the checked-in output.
#
# MPSKit has no golden-chain model, so the Hamiltonian is built here exactly as
# symtn-apps' `model::bond_term`: h = -J P^(1), the block of the coupled vacuum.

using MPSKit, TensorKit, TensorKitSectors, Random

const P = Vect[FibonacciAnyon](:τ => 1)

# MPSKit's hard-hexagon example `virtual_space`: D split evenly over the two
# sectors, so the total quantum dimension is ≈ D.
virtual_space(D) = Vect[FibonacciAnyon](s => round(Int, D / (1 + dim(FibonacciAnyon(:τ)))) for s in (:I, :τ))

function golden_chain(L, J)
    h = zeros(ComplexF64, P ⊗ P ← P ⊗ P)
    block(h, FibonacciAnyon(:I)) .= -J
    return FiniteMPOHamiltonian(fill(P, L), (i, i + 1) => h for i in 1:(L - 1))
end

label(c::FibonacciAnyon) = c == FibonacciAnyon(:I) ? "1" : "tau"

# D large enough that the discarded weight is far below the comparison
# tolerance at every L here (the full centre bond at L = 24 has total quantum
# dimension 89 + 144φ ≈ 322); tol and maxiter are MPSKit's defaults, spelled out.
const D = 128
const TOL = 1.0e-10
const MAXITER = 200
# The one non-default: with `tol_max = 1e-4`, the second sweep's eigensolves
# start from vectors whose residual is already below 1e-4, return them
# unchanged, and DMRG2 reports ϵ ≈ 1e-16 on a state still ~1e-9 off in E and
# ~1e-5 off in its spectrum. The fixture must pin the converged state, so the
# `updatetol` ceiling is lowered (the Rust side uses the same value).
const EIG_TOL_MAX = 1.0e-12

open(joinpath(@__DIR__, "fixtures", "golden_chain.txt"), "w") do io
    println(io, "# MPSKit 0.13.13, TensorKit 0.17.1, TensorKitSectors 0.3.10; generated by golden_chain.jl")
    println(io, "# DMRG2(trscheme = truncrank(D), tol = $TOL, maxiter = $MAXITER, alg_eigsolve = (; tol_max = $EIG_TOL_MAX)), Random.seed!(1234) per case")
    println(io, "# case L J total D | energy E | epsilon e | entropy bond S | spectrum bond sector values...")
    for L in (12, 16, 20, 24), J in (1.0, -1.0), total in (:I, :τ)
        Random.seed!(1234)
        H = golden_chain(L, J)
        right = Vect[FibonacciAnyon](total => 1)
        ψ₀ = FiniteMPS(L, P, virtual_space(D); right)
        ψ, envs, ϵ = find_groundstate(
            ψ₀, H, DMRG2(;
                trscheme = truncrank(D), tol = TOL, maxiter = MAXITER, verbosity = 0,
                alg_eigsolve = (; tol_max = EIG_TOL_MAX),
            )
        )
        E = expectation_value(ψ, H, envs)
        abs(imag(E)) < 1.0e-12 || error("complex energy $E")
        println(io, "case $L $J $(label(FibonacciAnyon(total))) $D")
        println(io, "energy ", real(E))
        println(io, "epsilon ", ϵ)
        for i in 1:(L - 1)
            println(io, "entropy $i ", real(entropy(ψ, i)))
            for (c, v) in pairs(entanglement_spectrum(ψ, i))
                println(io, "spectrum $i $(label(c)) ", join(string.(v), " "))
            end
        end
        @info "done" L J total E ϵ
    end
end
